"""Build switch/template.yaml from template.src.yaml and the instruction files.

A pasted template has to carry its instructions inline, but they are easier to
read and edit as separate files. So the source names them, and this writes the
one file to import in Switch Console:

    python switch/build_template.py

In template.src.yaml, a line "@include <path>" is replaced by that file, indented
to match. Inside an instruction file, "{{<path>}}" is replaced by that file.
Paths are relative to switch/. agents/tests/test_template.py checks the result
is up to date.
"""

import re
import sys
from pathlib import Path

SWITCH_DIR = Path(__file__).resolve().parent
SOURCE = SWITCH_DIR / "template.src.yaml"
TARGET = SWITCH_DIR / "template.yaml"
HEADER = "# Generated by switch/build_template.py from template.src.yaml. Edit those, not this.\n"
INLINE = re.compile(r"\{\{([\w./-]+)\}\}")


def instruction_text(relative: str) -> str:
    text = (SWITCH_DIR / relative).read_text(encoding="utf-8").strip()
    return INLINE.sub(lambda match: instruction_text(match.group(1)), text)


def build() -> str:
    lines = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("@include "):
            indent = line[: len(line) - len(line.lstrip())]
            for included in instruction_text(stripped.split(" ", 1)[1]).splitlines():
                lines.append(f"{indent}{included}".rstrip())
        else:
            lines.append(line)
    return HEADER + "\n".join(lines) + "\n"


def main() -> int:
    TARGET.write_text(build(), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(SWITCH_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
